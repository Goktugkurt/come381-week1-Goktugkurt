CREATE TABLE category (
    category_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name     text,
    is_age_restricted boolean DEFAULT false
);

CREATE TABLE supplier (
    supplier_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name  text,
    supplier_type  text,
    phone          varchar(20),
    status         text DEFAULT 'active',
    lead_time_days smallint DEFAULT 1
);

CREATE TABLE customer (
    customer_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name text,
    phone         varchar(20),
    credit_limit  numeric(12,2) DEFAULT 0,
    credit_used   numeric(12,2) DEFAULT 0,
    status        text DEFAULT 'active'
);

CREATE TABLE product (
    product_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode               varchar(13),
    product_name          text,
    category_id           integer CONSTRAINT fk_product_category
                          REFERENCES category(category_id) ON DELETE RESTRICT,
    preferred_supplier_id integer CONSTRAINT fk_product_preferred_supplier
                          REFERENCES supplier(supplier_id) ON DELETE SET NULL,
    cost_price            numeric(10,2),
    sale_price            numeric(10,2),
    stock_qty             integer DEFAULT 0,
    min_stock_qty         integer DEFAULT 0,
    max_stock_qty         integer,
    status                text DEFAULT 'active'
);

CREATE TABLE purchase_order (
    order_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id   integer CONSTRAINT fk_purchase_order_supplier
                  REFERENCES supplier(supplier_id) ON DELETE RESTRICT,
    order_date    date DEFAULT CURRENT_DATE,
    expected_date date,
    status        text DEFAULT 'draft'
);

CREATE TABLE purchase_order_item (
    order_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      integer CONSTRAINT fk_poi_order
                  REFERENCES purchase_order(order_id) ON DELETE CASCADE,
    product_id    integer CONSTRAINT fk_poi_product
                  REFERENCES product(product_id) ON DELETE RESTRICT,
    ordered_qty   integer,
    delivered_qty integer,
    unit_cost     numeric(10,2)
);

CREATE TABLE credit_risk_assessment (
    assessment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   integer CONSTRAINT fk_risk_customer
                  REFERENCES customer(customer_id) ON DELETE RESTRICT,
    risk_score    smallint,
    decision      text,
    assessed_at   timestamp DEFAULT CURRENT_TIMESTAMP,
    expires_at    date,
    notes         text
);

CREATE TABLE sale (
    sale_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer CONSTRAINT fk_sale_customer
                 REFERENCES customer(customer_id) ON DELETE RESTRICT,
    sold_at      timestamp DEFAULT CURRENT_TIMESTAMP,
    payment_type text DEFAULT 'cash'
);

CREATE TABLE sale_item (
    sale_item_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id       integer CONSTRAINT fk_sale_item_sale
                  REFERENCES sale(sale_id) ON DELETE RESTRICT,
    product_id    integer CONSTRAINT fk_sale_item_product
                  REFERENCES product(product_id) ON DELETE RESTRICT,
    quantity      integer,
    unit_price    numeric(10,2),
    unit_cost     numeric(10,2),
    discount_rate numeric(5,2)
);

CREATE TABLE shelf_sensor (
    sensor_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_code      varchar(20),
    product_id       integer CONSTRAINT fk_sensor_product
                     REFERENCES product(product_id) ON DELETE SET NULL,
    shelf_location   text,
    status           text DEFAULT 'online',
    last_reading_qty integer,
    last_seen_at     timestamp
);
